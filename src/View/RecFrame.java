    private void subcleanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_subcleanActionPerformed
        
        if(orderassignedrooms.getSelectedItem() == null)
            return;
        String selectedroom = orderassignedrooms.getSelectedItem().toString();
        
        String[] s = selectedroom.split("\t");
        s[0] = s[0].replaceFirst("RoomNumber: ", "");
        s[1] = s[1].replaceFirst(" Size: ", "");
        s[2] = s[2].replaceFirst(" isVip: ", "");
        s[3] = s[3].replaceFirst(" Price: ", "");
        s[4] = s[4].replaceFirst(" isReserved: ", "");
        
        Room r = new Room(s[0], Integer.parseInt(s[1]), Boolean.parseBoolean(s[2]), Integer.parseInt(s[3]), Boolean.parseBoolean(s[4]));
        
        rc.callForCleaner(r);
        ArrayList<Cleaning>allcleaning=fa.readCleaning();
        ArrayList<Cleaning>cl=new ArrayList();
        
        for(int i =0;i<allcleaning.size();i++)
        { 
            if(!allcleaning.get(i).getRoomnumber().equals(r.getRoomnumber()))
               cl.add(allcleaning.get(i));
        }
        cl.add(new Cleaning(r.getRoomnumber(), false));
        fa.resetfile("Cleaning");
        for(int i=0 ;i<cl.size();i++)
        fa.writeToFile("Cleaning",cl.get(i).toString());
    }//GEN-LAST:event_subcleanActionPerformed

