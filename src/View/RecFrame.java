    private void showavailablerooms()
    {
        ArrayList<Room> allrooms = fa.readRoom();
        
        int roomsize = Integer.parseInt(size.getValue().toString());
        String tier = tierroom.getSelectedItem().toString();
        Boolean isvip = false;
        
        if(tier.equals("Normal"))
            isvip = false;
        else
            isvip = true;
        
        showavailable.removeAllItems();
        
        for(int i =0; i<allrooms.size(); i++)
        {
            if(allrooms.get(i).getSize() == roomsize && allrooms.get(i).getIsVip() == isvip)
                showavailable.addItem(allrooms.get(i).toBoxString());
        }
    }
    
    
