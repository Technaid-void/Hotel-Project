    private void roominfotableActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_roominfotableActionPerformed
        ArrayList<Reserve> allreserves = fa.readReserve();
        ArrayList<Guest> allguests = fa.readGuest();
        
        JTable table = new JTable(allreserves.size() , 7);
        JFrame f = new JFrame();
        f.setSize(1000, 300);
        f.add(new JScrollPane(table));
        f.setVisible(true);
        
        table.getColumnModel().getColumn(0).setHeaderValue("Guest Id");
        table.getColumnModel().getColumn(1).setHeaderValue("Guest Name");
        table.getColumnModel().getColumn(2).setHeaderValue("Guest Age");
        table.getColumnModel().getColumn(3).setHeaderValue("Guest Nationality");
        
        table.getColumnModel().getColumn(4).setHeaderValue("Room Code");
        table.getColumnModel().getColumn(5).setHeaderValue("is Vip");  
        
        table.getColumnModel().getColumn(6).setHeaderValue("Date");
        
        
        
        
        int currentarr = 0;
        for(int row = 0; row<allreserves.size(); row++)
        {
                table.setValueAt(allreserves.get(currentarr).getId(), row, 0);
                
                for(int currg = 0; currg<allguests.size(); currg++)
                {
                    for(int reserveg = 0; reserveg < allreserves.size(); reserveg++)
                    {
                        if(allguests.get(currg).getNumber() == allreserves.get(reserveg).getId())
                            {
                                table.setValueAt(allguests.get(currentarr).getName(), row, 1);
                                table.setValueAt(allguests.get(currentarr).getAge(),row,2);
                                table.setValueAt(allguests.get(currentarr).getNationality(),row,3);
                            }
                    }
                }
                
                table.setValueAt(allreserves.get(currentarr).getRoomnumber(), row, 4);
                table.setValueAt(allreserves.get(currentarr).getIsVip(), row, 5);
                
                table.setValueAt(allreserves.get(currentarr).getDateofreserve(), row, 6);
                currentarr++;
 
        }
    }//GEN-LAST:event_roominfotableActionPerformed

