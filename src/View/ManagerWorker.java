    private void addworkerbuttonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addworkerbuttonActionPerformed
        String uname = workernametext.getText();
        String pass = workerpasstext.getText();
        String work = "";
       
        if(recradio.isSelected())
            work = "Receptionist";
        else if(manradio.isSelected())
            work = "Manager";
        else if(cwradio.isSelected())
            work = "Cleaner";
        
        
        if(workernametext.getText().trim().isEmpty())
        {
            JOptionPane.showMessageDialog(rootPane, "Enter a worker name");
            return;
        }
        
        if(workerpasstext.getText().trim().isEmpty())
        {
            JOptionPane.showMessageDialog(rootPane, "Enter a worker password");
            return;
        }
        int id = rd.generateWorkID(uname);
        Worker w = new Worker(uname,id,pass, work);
        mg.addWorker(w);
        
        
        JOptionPane.showMessageDialog(rootPane, "The id for the employee " + uname + " is " + id );
        workernametext.setText("");
        workerpasstext.setText("");
    }//GEN-LAST:event_addworkerbuttonActionPerformed

    private void workerslistActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_workerslistActionPerformed
        ArrayList<Worker> allworkers = fa.readWorker();
        JTable table = new JTable(allworkers.size() , 4);
        JFrame f = new JFrame();
        f.setSize(1000, 300);
        f.add(new JScrollPane(table));
        f.setVisible(true);
        
        table.getColumnModel().getColumn(0).setHeaderValue("Name");
        table.getColumnModel().getColumn(1).setHeaderValue("Id");
        table.getColumnModel().getColumn(2).setHeaderValue("Password");    
        table.getColumnModel().getColumn(3).setHeaderValue("Job");
        
        table.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        
        int currentarr = 0;
        for(int row =0; row<allworkers.size(); row++)
        {
                table.setValueAt(allworkers.get(currentarr).getName(), row, 0);
                table.setValueAt(allworkers.get(currentarr).getId(), row, 1);
                table.setValueAt(allworkers.get(currentarr).getPass(), row, 2);
                table.setValueAt(allworkers.get(currentarr).getJob(), row, 3);
                currentarr++;
 
        }
        
        InputMap inputMap = table.getInputMap(JTable.WHEN_FOCUSED);
        ActionMap actionMap = table.getActionMap();

        inputMap.put(KeyStroke.getKeyStroke(KeyEvent.VK_DELETE, 0), "deleteRow");
        actionMap.put("deleteRow", new AbstractAction() {
        @Override
        public void actionPerformed(ActionEvent e) {
            int[] selectedRows = table.getSelectedRows();
            DefaultTableModel model = (DefaultTableModel) table.getModel();
            
            // Delete rows (start from the end to avoid index shifting)
            for (int i = selectedRows.length - 1; i >= 0; i--) {
                Worker w = new Worker(
                        table.getValueAt(selectedRows[i], 0).toString(),
                        Integer.parseInt(table.getValueAt(selectedRows[i], 1).toString()),
                        table.getValueAt(selectedRows[i], 2).toString(),
                        table.getValueAt(selectedRows[i], 3).toString()
                );
                model.removeRow(selectedRows[i]);
                
                System.out.println(w);
                mg.removeWorker(w);
            }
        }
    });
    }//GEN-LAST:event_workerslistActionPerformed

