    private void loginbuttonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loginbuttonActionPerformed
        String idd = uid.getText();
        String password = ps.getText();
        Boolean idexists = false;
        
        ArrayList<Worker> workersaccount = fa.readWorker();
        idexists = false;
        try{
        for(int i =0; i<workersaccount.size();i++)
        {
            if(workersaccount.get(i).getId() == Integer.parseInt(idd))
            {
                idexists = true;
                if(workersaccount.get(i).getPass().equals(password))
                {
                    if(workersaccount.get(i).getJob().equals("Cleaner"))
                        //cleanerframe
                    {
                        ArrayList<Cleaning> allclean = cn.getAllRequests();

                        // Create table model with column names first
                        DefaultTableModel model = new DefaultTableModel();
                        model.addColumn("Room number");
                        model.addColumn("is Cleaned");
                        // Create table with the model
                        JTable table = new JTable(model);
                        JFrame f = new JFrame();
                        f.setSize(1000, 300);
                        f.add(new JScrollPane(table));
                        f.setVisible(true);
                        // Only populate if there's data
                        if (!allclean.isEmpty()) {
                            for (Cleaning cleaning : allclean) {
                                model.addRow(new Object[]{
                                cleaning.getRoomnumber(),
                                cleaning.getIsCleaned()
                            });
                         }
                } else {
                        JOptionPane.showMessageDialog(f, "No cleaning requests available", "Information", JOptionPane.INFORMATION_MESSAGE);
                }
                        

// Set up Enter key action
InputMap inputMap = table.getInputMap(JTable.WHEN_FOCUSED);
ActionMap actionMap = table.getActionMap();

inputMap.put(KeyStroke.getKeyStroke(KeyEvent.VK_ENTER, 0), "markAsCleaned");
actionMap.put("markAsCleaned", new AbstractAction() {
    @Override
    public void actionPerformed(ActionEvent e) {
        int selectedRow = table.getSelectedRow();
        if (selectedRow >= 0) { // Check if a row is selected
            String roomNumber = table.getValueAt(selectedRow, 0).toString();
            cn.setAsCleaned(roomNumber);
            model.removeRow(selectedRow);
        }
    }
});
                    }
                    if(workersaccount.get(i).getJob().equals("Receptionist"))
                        new RecFrame().setVisible(true);
                    if(workersaccount.get(i).getJob().equals("Manager"))
                        new ManagerFrame().setVisible(true);
                }
                else
                    JOptionPane.showMessageDialog(rootPane,"Wrong ID or password", "Failed to login", JOptionPane.ERROR_MESSAGE);
            }
        }
        if(idexists == false)
        {
            JOptionPane.showMessageDialog(rootPane,"Id doesn't exist", "Failed to login", JOptionPane.ERROR_MESSAGE);
        }
        }catch(Exception e){
            System.out.println(e);
            JOptionPane.showMessageDialog(rootPane,"Check your id and password", "Something wrong", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_loginbuttonActionPerformed

