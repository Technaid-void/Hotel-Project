    private void roomlistActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_roomlistActionPerformed
        ArrayList<Room> allrooms = fa.readRoom();
        JTable table = new JTable(allrooms.size() , 5);
        JFrame f = new JFrame();
        f.setSize(1000, 300);
        f.add(new JScrollPane(table));
        f.setVisible(true);
        
        table.getColumnModel().getColumn(0).setHeaderValue("Room number");
        table.getColumnModel().getColumn(1).setHeaderValue("Room size");
        table.getColumnModel().getColumn(2).setHeaderValue("vip");    
        table.getColumnModel().getColumn(3).setHeaderValue("Price");
        table.getColumnModel().getColumn(4).setHeaderValue("is Reserved");
        
        table.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        
        int currentarr = 0;
        for(int row =0; row<allrooms.size(); row++)
        {
                table.setValueAt(allrooms.get(currentarr).getRoomnumber(), row, 0);
                table.setValueAt(allrooms.get(currentarr).getSize(), row, 1);
                table.setValueAt(allrooms.get(currentarr).getIsVip(), row, 2);
                table.setValueAt(allrooms.get(currentarr).getPrice(), row, 3);
                table.setValueAt(allrooms.get(currentarr).getIsReserved(), row, 4);
                currentarr++;
 
        }
        
        InputMap inputMap = table.getInputMap(JTable.WHEN_FOCUSED);
        ActionMap actionMap = table.getActionMap();

        inputMap.put(KeyStroke.getKeyStroke(KeyEvent.VK_DELETE, 0), "deleteRow");
        actionMap.put("deleteRow", new AbstractAction() {
        @Override
        public void actionPerformed(ActionEvent e) {
            int[] selectedRows = table.getSelectedRows();
            DefaultTableModel model = (DefaultTableModel) table.getModel();
            
            // Delete rows (start from the end to avoid index shifting)
            for (int i = selectedRows.length - 1; i >= 0; i--) {
                Room r = new Room(
                        table.getValueAt(selectedRows[i], 0).toString(),
                        Integer.parseInt(table.getValueAt(selectedRows[i], 1).toString()),
                        Boolean.parseBoolean(table.getValueAt(selectedRows[i], 2).toString()),
                        Integer.parseInt(table.getValueAt(selectedRows[i], 3).toString()),
                        Boolean.parseBoolean(table.getValueAt(selectedRows[i], 4).toString()));
                model.removeRow(selectedRows[i]);
                
                System.out.println(r);
                mr.removeRoom(r);
            }
        }
    });
        
       
    }//GEN-LAST:event_roomlistActionPerformed

