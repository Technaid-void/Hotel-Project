    private void addroombuttonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addroombuttonActionPerformed
        
        String roomname = roomnumberbox.getText();
        int roomsize = (int) roomsizebox.getValue();
        String currenttier = roomtierbox.getSelectedItem().toString();
        Boolean isvip = false;
        
        int price = 1;
        
        if(roomnumberbox.getText().trim().isEmpty())
        {
            JOptionPane.showMessageDialog(rootPane, "Enter a name for the room");
            return;
        }
        
        if(currenttier.equals("Normal"))
            isvip = false;
        else if(currenttier.equals("VIP"))
            isvip = true;
        
        if(isvip == false)
            price = roomsize*100;
        else
            price = roomsize*200;
        
        roomprice.setText(Integer.toString(price));
        
        Room r = new Room(roomname, roomsize, isvip ,price, false);
        mr.addRoom(r);
        
        roomnumberbox.setText("");
        
    }//GEN-LAST:event_addroombuttonActionPerformed

